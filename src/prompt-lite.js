/**
 * **极简提示词**（2026-11-17）——
 * 给「本地小模型 / 整活向兜底模型」用的那一份，**几百字**而已。
 *
 * ## ⚠️ 内容从哪来（2026-11-17 用户：「其他号也得做一份一样的极简词，以后新建号自动搜集时也要新建」）
 *
 * ① **优先**读这个号人设包里的 `personas/<id>/prompt/lite.md` —— 每个号一份，各写各的 ✓
 * ② 没写就用**通用骨架** + 自动填名字（`persona.shortName()`）⇒ 新建号零配置也能跑 ✓
 *
 * ⚠️ `promptFile()` 是**热读**的（按 mtime 判断）⇒ 改 lite.md 刷新即生效，不用重启 ✓
 * ⚠️ 而**本文件**是代码 ⇒ 改这里要重启进程才生效。
 *
 * ## 为什么要单独一份（别删这段）
 *
 * 正常那条路的提示词实测是 **6.3 万 ~ 13.2 万字**（人设 + 知识库 + 群聊记录 + 工具说明…），
 * 换成 `4~9 万 token`。而本地小模型（0.5B / 1.5B）：
 *   · 上下文窗口只有 32K token ⇒ **塞不下** ✗
 *   · 就算塞得下，CPU 上把 4 万 token 读一遍要**几十秒到几分钟** ⇒ 消息早就过时了 ✗
 *
 * ⇒ 勾了「使用极简提示词」的那个提供商，走这一份：只留"你是谁 / 怎么说话 / 什么不做"，
 *   别的（知识库、记忆、工具、剧情）**全部不进提示词** ⇒ 小模型也能在几秒内回一句话 ✓
 *
 * ## 写这份提示词的取舍
 *
 * · 小模型**记不住**长篇规则，所以规则条数压到 8 条以内、每句都短 ✓
 * · 小模型**容易跑偏**（复读、解释自己、编格式），所以要明写"只输出那句话" ✓
 * · 名字里**别出现"客服"** —— 实测 0.5B 会照字面演客服腔（「您好，请问有什么可以帮助您的吗」）✗
 * · 质量本来就不指望（整活向兜底），**只要求"像个人在说话"** ✓
 *
 * @param {{ at?: string, group?: boolean }} opt
 *   `at` = 现在跟谁说话（"群里某人" / 某人昵称），没有就不提
 * @returns {string} 系统提示词
 */
import * as persona from './persona.js';
// ⚠️ 2026-11-20 加：主人说话时要把 `knowledge/relationship.md` 拼进来（见 `ownerBlock()`）
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { KNOWLEDGE_DIR } from './config.js';

/**
 * **静态区 / 动态区的分界标记**（2026-11-23，缓存命中率 85% → 97% 的那一刀）。
 *
 * `buildLitePrompt()` 把它插在"一整天都不变"的内容之后；
 * `bot.js` 在构造 `messages` 时按它 split 一次：
 *   · 前半段 ⇒ `messages[0].content`（system，**永远不变**）
 *   · 后半段 ⇒ 单独一条 user "背景"消息
 *
 * ⚠️ 为什么必须拆：Qwen3 的 chat template 把 `tools` 渲染在 system **之后**，
 *   而 24 个工具 = 4,542 token ⇒ system 尾巴一动，这 4,542 就白算 ✗
 * ⚠️ 别把标记改成会在正文里出现的样子（它是内部标记，不会给模型看到）。
 */
export const LITE_DYNAMIC_MARK = '@@LITE-DYNAMIC@@';

export function buildLitePrompt(opt = {}) {
  const at = String(opt.at ?? '').trim();
  /* ══════════════════════════════════════════════════════════════════════
   * ⚠️⚠️⚠️ 2026-11-21 加 9 个状态注入块（用户给的 12 项清单，去掉 6/10/11）
   *
   *   用户原话：「**除了 6，10，11 其他都加，7 收敛为工具。这些都是必须的，
   *              要么就压缩之前的提示词**」
   *
   *   ⇒ 加：① 当前时间 ② 剧情状态 ③ 电量档 ④ 生活状态 ⑤ 好感度
   *          ⑦ 提醒（→ 已经是工具 `set_reminder`/`cancel_reminder`，不注入）
   *          ⑧ 她刚发过什么 ⑨ 冷场时长 ⑫ 今天的日常排期
   *   ⇒ 不加（用户说"删了，现在没用了"）：⑥ 群里在场者 ⑩ 说话特征 ⑪ 表情冷却
   *
   *   ⚠️ **全部由调用方传进来**（`opt.*`）——这个文件保持"纯拼装"，不自己去读状态机，
   *      免得它跟 `bot.js` 抢同一个数据源、也免得测试时到处要 mock ✓
   *   ⚠️ 读不到 / 不适用 ⇒ 返回空串（`.filter(Boolean)` 会剔掉）⇒ **不占 token** ✓
   *   ══════════════════════════════════════════════════════════════════════ */

  /** ① 当前时间：几号、周几、几点。⚠️ 每轮都变 ⇒ 必须在固定段之后 */
  function nowBlock() {
    const t = String(opt.now ?? '').trim();
    if (!t) return '';
    /* ⚠️⚠️ 2026-11-24 补（用户：「图三下午变成大晚上」）——
     *   原来这句只说「**问**'现在几点'就照这儿说」⇒ 她**主动**说"你大晚上问这个"时
     *   不受它管，就按感觉编了（实测 15:22 的回复里写「大晚上」）✗
     *   ⇒ 改成：**她自己提任何早晚的话之前**，也得以这一行为准。 */
    return (
      `\n# 现在是什么时候\n${t}\n` +
      '（**问"现在几点""今天周几"就照这儿说**，别自己编；也用这个判断"这么晚了""才几点"这类话）\n' +
      '⚠️ 不只是被问的时候：**你自己要说"几点了""这么晚了""大晚上""才这个点"之前，先回头看上面这一行** ——\n' +
      '现在写的是几点就是几点，别按感觉编。'
      // ⚠️ 「放学 = 离开学校」那条**不在这里** —— 它放在 `bot.js` 的 `timeText()` 里，
      //    那样全量和 lite 共用一份，不会两边写两套（也别再往这儿加回来）✓
    );
  }

  /** 🖼️ 识图结果（⚠️⚠️ 2026-11-21 加：lite 模式**一直没拼过** ⇒ 她明明识图了却说"看不到图" ✗） */
  function visionBlock() {
    const v = String(opt.vision ?? '').trim();
    if (!v) return '';
    /* ⚠️ 必须**原样**拼（`visionBlock()` 自己带 `# 【视觉识别结果】` 那套说明）——
     *   里面已经写了「你已经看过这张图了，绝对不要说我看不到图」✓
     *   ⚠️ 位置放在"最近发生的事"之后、"实时数据"之前：离他要回的那句近 ✓ */
    return `\n${v}`;
  }

  /** 👉 戳一戳（⚠️⚠️ 2026-11-22 加）
   *
   *   用户原话：「**但是戳一戳回复的一直都是默认的被戳，而不是被捏或者其他**」
   *
   *   真因：`bot.js` 那边**已经**把动作文案读出来了（`event._pokeText`，实测日志
   *   `动作="捏了捏的脸"`），全量提示词也有一段专门讲（`if (event._poke)` 那 100 多行）。
   *   但 **lite 模式走的是这个文件，而这里一个字都没有 `poke` / `戳`** ✗
   *   ⇒ 她收到的 user 正文就 5 个字 `[戳一戳]`：不知道是谁戳的、不知道是"捏了捏的脸"
   *     还是"拍了拍"，也不知道该怎么回 ⇒ 只能回一句笼统的"被戳了" ✗✗
   *
   *   ⚠️ 三个都要给：**是谁**（名字+QQ）、**什么动作**（原文）、**怎么接**
   */
  function pokeBlock() {
    const p = opt.poke;
    if (!p) return '';
    const who = String(p.who ?? '').trim();
    const uid = String(p.uid ?? '').trim();
    const act = String(p.pt ?? '').trim();
    if (!who && !uid) return '';
    const whoTxt = who ? `${who}（QQ ${uid}）` : `QQ ${uid}`;
    return [
      '',
      '# 有人戳了你一下',
      `是**${whoTxt}**戳的 —— 就这一个人，别安到别人头上。`,
      act
        ? `他用的动作是「**${act}**」—— 这是 QQ 戳一戳的自定义文案，原文就这几个字，不是你翻译的。`
        : '他不是打了字，是伸手戳了你一下。',
      '',
      '怎么回：',
      '- **接住那个动作本身**：他捏你脸你就说捏脸的事，拍你你就说拍，别笼统地说"被戳了一下"。',
      '- 一两句就够，十几二十个字。',
      '- 别每次回同一句。',
      // ⚠️⚠️ 2026-11-24：**必须写成"默认动作"，不能写成"想还手就调"** ——
      //    实测（8 条戳一戳 × 3 版）：现状 0/6、「想真还手就调」0/6、
      //    「还手是默认的，先调 poke_back 再说话」**4/6**、再加"懒得理才不动手" **5/6**。
      //    4B 对条件式（想…就…）几乎零响应，对"先做 X 再说 Y"才照做 ✓
      //    这条放在这个块里（提示词最末尾）：静态区那份 lite.md 的 LITE-POKE 段隔得太远，压不住。
      '- **还手是默认的**：被戳了就先调 `poke_back` 把那一下还回去，再回你的话。' +
        '只有你确实懒得理他，才只回一句、不动手。',
    ].join('\n');
  }

  /** 👥 群友信息（⚠️⚠️ 2026-11-21 加：lite 也注入，不然她不知道群里谁是谁） */
  function groupPeopleBlock() {
    const g = String(opt.groupPeople ?? '').trim();
    if (!g) return '';
    return `\n# 群里这些人（谁是谁）\n${g}\n（有人问「XXX 是谁」⇒ **先在这张表里找**，找不到就说"不太清楚"，别猜）`;
  }

  /** 🙋 **主动接话时**必带的那句（⚠️⚠️ 2026-11-21 加，用户原话）——
   *
   *   「**如果是因为模型判回的话，提示词里一定要有这段话：
   *     这段话不是对你说的，不要把自己当成主角，你只是一个中途插话的人**」
   *
   *   ⚠️⚠️ **只在 `voluntary`（主动接话）时加，而且必须放在末尾动态区** ——
   *      它每轮有/没有都在变，放到 lite.md 前面会把那 2 万多 token 的前缀缓存全废 ✗
   *   ⚠️ 位置：`said` 之前（离他要回的那句最近，权重也够）✓ */
  function voluntaryBlock() {
    const v = String(opt.voluntary ?? '').trim();
    if (!v) return '';
    return [
      '',
      '# 🚨 先看清：**这段话不是对你说的**',
      '',
      '**你不是主角。** 上面那些话是**别人之间在聊**，你只是**中途插一句的人** ——',
      '所以：',
      '',
      '- 🚫 **别把"你"当成自己**（那个"你"指的很可能是别人）',
      '- 🚫 **别把他说的话当成"在要求你"**（他可能在跟别人说、可能只是感叹）',
      '- 🚫 **别抢着回答不属于你的问题** —— 你插一句是因为**有话可说**，不是因为"轮到你答"',
      '- ✅ 你插话的姿势：**顺着聊、接个梗、补一句看法** —— 就像群里随口接一句那样',
      '- ✅ 说错了没人怪你，但**别装成是他在问你** ✗',
    ].join('\n');
  }

  /** ② 剧情状态：在不在演、演到第几轮 */
  function questBlock() {
    const q = opt.quest;
    if (!q || !q.live) return '';
    const r = Number(q.rounds) || 0;
    return `\n# 剧情状态\n正在演剧情${r > 0 ? `，已经到第 ${r} 轮` : ''}。${String(q.hint ?? '').trim()}`;
  }

  /** ③ 电量档：只有真的低电量才说 */
  function batteryBlock() {
    const b = String(opt.battery ?? '').trim();
    return b ? `\n# 你的电量\n${b}` : '';
  }

  /**
   * 把一个"可能是对象"的字段转成能拼进提示词的一行文本。
   *
   * ⚠️⚠️ 2026-11-23 修（实测：提示词里 `# 此刻的状态` 下面就是 `[object Object]`）——
   *   `bot.js` 传进来的 `life: lifeFS.status(gid)` 和 `todayPlan: lifeFS.todayPlan(gid)`
   *   都是**对象**，这里原来是 `String(opt.life)` ⇒ 拼出来就是 `[object Object]` ✗
   *   ⇒ 这两段（"她此刻在干什么""今天安排了什么"）**一个字都没进提示词**，
   *     等于白占位置，还让提示词内容不稳定（影响缓存）。
   */
  function toText(v) {
    if (v == null) return '';
    if (typeof v === 'string') return v.trim();
    if (typeof v === 'number' || typeof v === 'boolean') return String(v);
    if (Array.isArray(v)) return v.map(toText).filter(Boolean).join('、');
    if (typeof v === 'object') {
      for (const k of ['text', 'desc', 'summary', 'label', 'doing', 'hint', 'name']) {
        const s = v[k];
        if (typeof s === 'string' && s.trim()) return s.trim();
      }
      const bits = [];
      for (const [k, val] of Object.entries(v)) {
        if (val == null || val === '' || typeof val === 'object') continue;
        bits.push(`${k}：${val}`);
      }
      return bits.join('　');
    }
    return '';
  }

  /** ④ 生活状态：她现在"正在干什么" */
  function lifeBlock() {
    const l = toText(opt.life);
    return l ? `\n# 此刻的状态\n${l}` : '';
  }

  /** ⑤ 好感度/关系档 */
  function affinityBlock() {
    const a = String(opt.affinity ?? '').trim();
    return a ? `\n# 你跟他现在的关系\n${a}` : '';
  }

  /** ⑧ 她刚发过什么（防重复说同一句） */
  function myRecentBlock() {
    const m = String(opt.myRecent ?? '').trim();
    if (!m) return '';
    return `\n# 你刚才已经说过的话（**别把意思重复一遍**，换句话或者往下说）\n${m}`;
  }

  /** ⑨ 冷场时长 */
  function silenceBlock() {
    const s = String(opt.silence ?? '').trim();
    return s ? `\n# 群里的冷场情况\n${s}` : '';
  }

  /** ⑫ 今天的日常事件排期 */
  function todayPlanBlock() {
    const p = toText(opt.todayPlan);
    return p ? `\n# 你今天安排过的事\n${p}` : '';
  }

  // ⚠️⚠️ 2026-11-18 加（实测事故，23:02 爱音那次）——
  //    极简模式原来**一条历史都不带**，结果 <主人> 问「你是谁」，她回「我用 AE 做的」✗✗
  //    小模型手里只有那 261 字身份，完全不知道刚才在聊什么 ⇒ 只能瞎接。
  //    ⇒ 现在塞最近 5 条对话（"名字：话" 的短格式，总量 < 700 字，0.5B 吃得下）✓
  //    ⚠️ 仍然**不塞**知识库 / 记忆 / 剧情 / 工具说明 —— 那些才是小模型接不住的东西 ✓
  /* ⚠️ 2026-11-23：600 → **2400 字**（用户：「10 条太少了，改成 60 条」）——
   *   上游已经给到 60 条了，这里还卡 600 字的话**等于白给**（只进得了 3~4 条）✗
   *   ⚠️ 2400 字 ≈ 1,800 token，全在动态段 ⇒ 每轮重算，首字会涨 ~0.9 秒、命中率 96% → ~92% */
  const recent = String(opt.recent ?? '').trim().slice(0, 2400);
  // ⚠️⚠️⚠️ 2026-11-18 加（用户：「**当极简提示词时直接把对面说的话包装成真正对面在说话的段落**」）——
  //    实测过的事：小模型**分不清 user / assistant 角色**，长上下文对它就是"续写素材"
  //    ⇒ 问「你是谁」回「区区区区」（抄历史）、问一句原样复读一句 ✗
  //    解法就是这句：**把"他刚说了什么"当人话写进提示词**，它不用猜谁在说话 ✓
  const said = String(opt.said ?? '').trim().slice(0, 300);
  // ⚠️⚠️ 2026-11-18 加（用户：「**服务器的数据可以照常拿吗，这个模型上下文应该长很多吧**」）——
  //    原来极简模式把**实时数据也一起扔了** ⇒ 问「服务器多少人」它只能编（实测编了个「132 人」「20000 人」）✗
  //    1.5B 上下文 32K 撑得住几千字，但**prefill 是 CPU 跑的**，塞太满会慢到没法聊
  //    ⇒ 给**一小段**（500 字以内：在线人数、版本这类最常问的），照着实数据说 ✓
  const live = String(opt.live ?? '').trim().slice(0, 500);

  /**
   * ⚠️⚠️ 2026-11-20 加（用户：「**relationship.md 着重注入一下**」）——
   *
   *   这份 `knowledge/relationship.md` 是**专门讲"对主人和对群友哪里不一样"**的私人文件
   *   （里面明写「本文件优先级高于人设」「群友不适用」）。
   *   它比"可以更松一点"那一句有料得多 ⇒ 主人说话时**把全文拼进来** ✓
   *
   *   ⚠️ **必须在动态区、而且是最后一项**：
   *     · 写进 lite.md 静态段 ⇒ 群友也能看到，她对谁都端不住 ✗
   *     · 放在 `own` 前面 ⇒ 会毁掉那 5 万 token 的前缀缓存 ✗
   *     · 现在它接在 `isOwner ? … : ''` 里 = 数组最后 ⇒ 前缀完全不变，缓存照旧命中 ✓
   *   ⚠️ 读不到就返回空串（不报错、不影响出话）✓
   */
  function ownerBlock() {
    /* ⚠️ 2026-11-20：`relationship.md`（对他和对群友的区别）+ `owner.md`（他本人的事/习惯/偏好）
     *    **两份都只在主人说话时拼** —— 它们都是"只有他才能得到的东西"，
     *    给群友看到就等于把私人关系摊开了 ✗
     *    ⚠️ 位置不变：仍然接在 `isOwner ? … : ''` 里 = 数组最后 ⇒ 前缀缓存不受影响 ✓ */
    const readOne = (file) => {
      try {
        const raw = readFileSync(join(KNOWLEDGE_DIR, file), 'utf8');
        const body = String(raw ?? '')
          .replace(/<!--[\s\S]*?-->/g, '')
          .split('\n')
          .filter((l) => {
            const t = l.trim();
            if (t.startsWith('>')) return false; // 引用块：给改这个文件的人看的说明
            if (/^\*\*（?20\d\d-/.test(t)) return false;
            return true;
          })
          .join('\n')
          .replace(/\n{3,}/g, '\n\n')
          .trim();
        return body;
      } catch {
        return '';
      }
    };

    const rel = readOne('relationship.md');
    const own = readOne('owner.md');
    if (!rel && !own) return '';

    let out = '';
    if (rel) out += `\n# 他跟别人不一样（这份是写给你的，别对群友用）\n\n${rel}\n`;
    if (own) out += `\n# 你记着的、关于他的事（**别当面背出来**，用的时候自然带上就行）\n\n${own}\n`;
    return out;
  }
  // ⚠️⚠️ 2026-11-18 加（用户：「**再加一段对主人关系的提示词**」）——
  //    ⚠️ 这一段必须是**动态**的：写在 lite.md 里就等于"所有人都看到他是你老板"，
  //    而她跟路人说话时也带着那句 ⇒ 看不出区别 ✗
  //    ⇒ 只在**当前说话的人就是主人**时加一句 ✓（判据在 `bot.js`：`user_id === ownerQQ`）
  const isOwner = opt.owner === true;
  /**
   * ⚠️⚠️ 2026-11-20 加：**最近发生的事**（`knowledge/recent-events.md`）
   *
   *   用户：「**找一下所有动态提示词的地方，比如最近的大事之类的库，注入这类对回答质量
   *   提升大而且字数少**」
   *
   *   ⇒ 这类内容：**几百字，但决定"她对不对得上现在"**（谁换了电脑、服务器迁了域名、
   *     群里出过什么事、外面最近在玩什么梗）。原来完全没有这个层 ——
   *     她只知道"静态人设"，不知道"最近发生了什么" ✗
   *
   *   ⚠️ 对**所有人**都拼（不像 relationship/owner 只给主人）——
   *     群里的事、服务器的事，群友也该知道 ✓
   *   ⚠️ 位置：紧跟 lite.md（**靠前**）；只有几百字，不会挤掉别的内容 ✓
   *   ⚠️ 读不到 / 只剩空占位 ⇒ 整段不拼（别塞一堆空标题）✓
   */
  function recentEventsBlock() {
    try {
      const raw = readFileSync(join(KNOWLEDGE_DIR, 'recent-events.md'), 'utf8');
      const body = String(raw ?? '')
        .replace(/<!--[\s\S]*?-->/g, '')
        .split('\n')
        .filter((l) => {
          const t = l.trim();
          if (t.startsWith('>')) return false; // 引用块：给维护者看的说明
          if (/^（还没记/.test(t)) return false; // 空占位
          if (/^（同上/.test(t)) return false;
          return true;
        })
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trim();
      const hasContent = body.split('\n').some((l) => l.trim() && !l.trim().startsWith('#'));
      if (!hasContent) return '';
      return `\n# 最近发生的事（**这些是"现在"的背景，别当成老黄历**）\n\n${body}\n`;
    } catch {
      return '';
    }
  }
  // ── ① 这个号**自己那份**：`personas/<id>/prompt/lite.md` ──
  // ⚠️⚠️ 2026-11-17 加（用户：「**其他号也得做一份一样的极简词，以后新建号自动搜集时也要新建**」）——
  //    原来这段是**写死在代码里**的（只写着"小祥"）⇒ 谷雨/爱音用同一份就会自称小祥 ✗
  //    ⇒ 现在跟人设包走：每个号读自己包里的 `prompt/lite.md`（`promptFile` 是**热读**的，
  //      改完刷新就生效，不用重启）✓
  let own = '';
  try {
    // ⚠️ `promptFile()` 是**原样返回全文**的（不剥 HTML 注释）⇒ 这里自己剥掉，
    //    免得包里写的 `<!-- 说明 -->` 被当成提示词喂给模型 ✗
    own = String(persona.promptFile('lite') ?? '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .trim();
  } catch {
    /* 读不到就当没写 */
  }
  if (own) {
    /* ⚠️⚠️⚠️ 2026-11-23 **按"变不变"重排**（缓存命中率 85% → 目标 96%）——
     *
     *   原来这个数组是**按语义**排的（识图紧跟群友表、`ownerBlock` 压在最后），
     *   结果：`visionBlock` 在第 4 项、`ownerBlock`（<主人> 关系 3148 + 专属知识 2841）
     *   在最后一项 ⇒ **任何一个动态段一变，后面 6,000 字的专属资料就全部白算** ✗
     *   实测：<主人> 轮 32,337 token 只命中 27,330（84.5%），而群友轮能到 96.3%
     *   —— 差的正是被动态段"垫在下面"的 ownerBlock ✗
     *
     *   ⇒ 顺序改成 **静态在前、动态在后、识图最后**：
     *     · 前三项（lite.md / 群友表 / ownerBlock）一天之内完全不变 ⇒ 吃满前缀
     *     · 后面全是"每轮会变"的（时间 / 实时数据 / 好感度 / 群聊 / 他刚说的 / 戳一戳）
     *     · `visionBlock` 挪到**最末尾**：它每换一张图就不同，放前面等于每轮砍一刀
     *   ⚠️ 别再把 `ownerBlock` 挪回最后 —— 那是这次 85% 的直接原因。 */
    return [
      own,
      /* 静态：群友表 + 他专属的相处资料（都会一整天才变，放最前面吃满缓存） */
      groupPeopleBlock(),
      isOwner
        ? // ⚠️⚠️ 2026-11-20 改（用户：「**relationship.md 着重注入一下**」）——
          //    原来只有一句"可以更松一点"，太薄。这份私人关系文件（谁是谁、对谁什么态度、
          //    哪些分寸不适用于他）才是"像活人"的关键 ⇒ **主人说话时把全文拼进来** ✓
          //    ⚠️ **只在主人说话时**：里面明写「本文件优先级高于人设」「群友不适用」，
          //      对所有人生效会让她对群友也端不住 ✗
          `\n${ownerBlock()}` +
          '\n⚠️ 现在这句话是你老板 <主人> 说的 ⇒ 上面那些分寸**都以他为准**（可以更松：开玩笑、耍赖、抱怨两句都行）。'
        : '',
      // 每天才变一次（`knowledge/recent-events.md`）
      recentEventsBlock(),
      /* ⚠️⚠️⚠️ 2026-11-23 **静态区到此为止**（这条标记是缓存的分界线）——
       *
       *   为什么要有它：llama.cpp 的 Qwen3 模板把 `tools` 渲染在 **system 内容之后**
       *   （`<|im_start|>system\n{system}\n# Tools\n{tools}<|im_end|>`），
       *   而 `tools` 有 **4,542 token**（24 个工具，7,172 字 JSON）。
       *   ⇒ 只要 system 的**最后几个字**变了，`tools` 就整段作废 ⇒ 每轮白算 4,542 token ✗
       *
       *   实测（`logs/_prompt-*.prev/last.txt` 相邻两轮）：
       *     字符级公共前缀 **46,489 字 / 47,455 字 = 98.0%**
       *     可 `spend-detail` 里 `cached/pt` 只有 **29,708 / 34,945 = 85%**
       *     差额 5,237 = 610(尾部变化) + 4,542(tools) + 340(历史) ← 正好对上 ✓
       *   ⇒ `bot.js` 按这条标记把后半段**移出 system**（拼成一条"背景"消息），
       *     system 就 100% 稳定 ⇒ `tools` 也能复用 ⇒ 命中率 85% → 97% ✓
       *   ⚠️ 别删这条标记；也别把动态段重新塞回它前面 */
      LITE_DYNAMIC_MARK,
      // ── 以下全是每轮会变的（顺序只影响可读性，都压在末尾不伤前缀）──
      live ? `\n实时数据（**他问到时就照这里说，别自己编数字**）：\n${live}` : '',
      questBlock(),
      batteryBlock(),
      lifeBlock(),
      affinityBlock(),
      myRecentBlock(),
      silenceBlock(),
      todayPlanBlock(),
      /* ⚠️⚠️ 2026-11-24 改（用户：「**群历史聊天给模型参考的时候要有权重，从近到远**」）——
       *   原来标题是「之前**别人**说过的话（看明白在聊什么就行，别把他们的句子抄回来）」
       *   ⇒ 语气把她**往后推**：她只当背景看，不去接最近那一句 ✗
       *   现场（截图）：他先回了个「对」，紧接着只 @ 了她一下 —— 她回「啧，怎么又@我」，
       *     完全没接那个「对」。
       *   ⇒ 改成"越往下越新，最后一行最该接"，并且最后一行在 `recentText` 那边会被标出来 ✓ */
      recent ? `\n最近群里在聊什么（**越往下越新，最后一行是他刚说的 —— 先接这一句**）：\n${recent}` : '',
      /* ⚠️ 2026-11-21：**主动接话时**那句「这段话不是对你说的」（每轮有/没有都在变）✓ */
      voluntaryBlock(),
      said
        ? `\n${at || '群里有人'} 刚对你说：「${said}」\n你接着这句话回一句（**用你自己的话说，别把他那句重复一遍**）。`
        /* ⚠️⚠️ 2026-11-24 加：**只 @ 了但没打字**（最常见的一种）——
         *   这时 `said` 是空的，原来这段话整段不注入 ⇒ 她只知道"被 @"，
         *   于是回「怎么又@我」（截图现场）✗
         *   ⇒ 明确告诉她：他要你接的是**上面最近那一句**，别把"又@"当正事 ✓ */
        : at
          ? `\n${at} 刚 **@ 了你，但没打字** —— 他不是在抱怨、也不是在问"你怎么了"，` +
            '他要你接的是**上面最近那一句**（最后一行）。接着说那件事，别只说一句"又@我"。'
          : '',
      pokeBlock(),
      at ? `\n现在跟你说话的是：${at}` : '',
      /* ⚠️ 2026-11-21 加：**当前时间**（用户点名的「现在几点她答不上」）——
       *   ⚠️ 只到小时（分钟每轮都变，见 `timeText()` 那条注释）✓ */
      nowBlock(),
      /* ⚠️ 2026-11-23：**识图挪到最后** —— 换一张图整段就不同，
       *   放前面（原来第 4 项）等于每轮把后面所有内容重算一遍 ✗ */
      visionBlock(),
    ]
      .filter(Boolean)
      .join('\n');
  }

  // ── ② 没写 ⇒ **自动拼一份**（新建号零配置也能用）──
  //    ⚠️ 名字从这个号的人设包里取，取不到才用"小祥"兜底 ✓
  //    ⚠️ 这一份是**通用骨架**：小模型只要能"说人话"就够了，不指望它演人设
  let name = '小祥';
  try {
    name = persona.shortName() || persona.charName() || '小祥';
  } catch {
    /* ignore */
  }
  return [
    // ⚠️⚠️ 2026-11-17 实测改（0.5B 版）：原来写的是「你叫客服小祥，在一个 QQ 群里当客服」，
    //    结果它每条都回「您好，请问有什么可以帮助您的吗？」——
    //    **小模型对"客服"这个词是照字面演的**，写什么身份就演什么身份 ✗
    //    ⇒ 身份里**去掉"客服"**，改成"在群里跟人闲聊"这种**正面描述** ✓
    //    （对 0.5B 来说，"别做 X"几乎无效，"你是 Y"才有点用）
    `你叫${name}，在一个 QQ 群里跟一群人闲聊。`,
    '',
    '说话的样子：手机打字，随便，像跟同学讲话。',
    '一次就回一两句，十几二十个字，别写长。',
    '不用敬语，不用「您」「请问」「稍等」「很高兴为您服务」这种话。',
    '不用 markdown、不列清单、不加引号。',
    '',
    '别的：',
    '· 不知道就说不知道，别编。',
    '· 做不到就说做不到。',
    '· 不聊政治、色情、暴力。',
    '· 不批准任何申请，也不承诺重启服务器。',
    '',
    '⚠️ 只输出你要说的那一句话，不要解释、不要加前缀、不要写你的思考。',
    recent ? `\n最近说过的话（接着上面这些说，别答非所问）：\n${recent}` : '',
    /* ⚠️ 2026-11-22：戳一戳放在 `recent` **后面**（离他要回的那句最近）——
     *   放前面会被一长串群聊记录淹没，小模型就只看得见"有人在说话"了 ✗ */
    pokeBlock(),
    at ? `现在跟你说话的是：${at}` : '',
  ]
    .filter((x) => x !== '')
    .join('\n');
}

