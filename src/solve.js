/**
 * 「解题模式」—— 群里有人发数学 / 物理 / 化学题时，切换到**认真解题**的行为。
 *
 * 用户需求（2026-09-12）：
 *   「a，然后可以加个解题模式，再提升token上限」
 *
 * 起因（真实截图）：
 *   luomoSan 发了道折叠最值的几何题，机器人回了：
 *     「行，是我看漏了。给我两分钟」        ← **空头承诺，说完就没下文**
 *     「这题第三问翻折最值，出题人下手够狠的」 ← 只评论难度，不给答案
 *     「在算呢别催，这种题得动笔，我又不是计算器」 ← 找借口 + 顶回去
 *   <主人> 回：「给答案，别光评论」
 *
 * 三个毛病：
 *   ① **承诺做不到的事**（"给我两分钟" —— 它没有"两分钟后"这个机制）
 *   ② **只会评论题目，不去真算**
 *   ③ **被催了就顶回去**（"我又不是计算器"——把催促当冒犯）
 *
 * 这个模块负责：
 *   · 识别"这是道题"（数学/物理/化学/求值/证明…）
 *   · 给出一段**解题专用提示词**（真推导、给最终答案、算不出来就说算不出来）
 *   · 提供一个**更大的 max_tokens**（推理模型的思考链很吃 token）
 */
import { config } from './config.js';
import { log } from './log.js';

/**
 * 这段提示词会被塞进系统提示词，专门管「解题」这件事。
 */
export const SOLVE_GUIDE = `# 【解题模式】对方发来的是一道**题目**，这次要**真的解出来**

⚠️ 群里真实踩过（2026-09-12）：有人发了道折叠最值的几何题，
机器人回了「行，是我看漏了，**给我两分钟**」→ 然后**没有下文**；
被催了又回「这题翻折最值，出题人下手够狠的」（**只评论难度，不给答案**）
和「在算呢别催，这种题得动笔，**我又不是计算器**」（**找借口 + 顶回去**）。
用户当场说「**给答案，别光评论**」。

## 所以这次照这个来

### 1. 真去算，别评论题目
- **不要**说「这题出得真狠」「这题有点意思」「这题需要动笔」这种话 ——
  **那是在评论，不是在做题。** 对方要的是答案。
- **在心里把推导走完**，然后把**关键步骤 + 最终答案**说出来。

### 2. 给答案（最重要）
- 答案要**明确、具体**：数值就写数值，证明就给完整推理链，选择题就说选哪个。
- 格式：**先给结论，再说关键推导**。别把过程写成长篇大论然后忘了给答案。
- 允许多写（这题目的就是要算对），但也**别把草稿全倒出来** ——
  写「能看出你是真的算过」的那几步就够。

### 3. ❌ 绝对不许说这几句（都踩过）
- ❌「**给我两分钟**」「等我算算」「稍等一下」——
  **你根本没有"过两分钟再回来"这个机制**，说完就没下文了，
  对方会觉得你在放他鸽子。**要么现在算，要么现在说算不出来。**
- ❌「我又不是计算器」「别催」「这种题得动笔」—— 被催了别顶回去。
- ❌「这题我不会」之后**不解释为什么**。

### 4. 算不出来就**老实说**（这是允许的，而且比糊弄强）
- 说清楚卡在哪：「条件里 D 点的位置我读不准」「这一步推不下去了」。
- 或者**问一个具体的问题**（不是泛泛地要题）：
  「图上 BD 那段标的数字能再发清楚点吗」。
- **绝对不要**用"评论题目"或"空头承诺"来把这一轮混过去。

### 5. 题目信息不全时
- 先把**你已经读到的**部分说清楚（证明你真看了），
  再说**具体缺什么**，然后**问那一个点**。
- 不要问「题目呢？」「你要我解什么？」——那等于没看图。`;

/**
 * 判断这条消息是不是「一道题」。
 *
 * ⚠️ 判据要**收着点**，别把闲聊误判成题目（那会让回复突然变得很正式）。
 *    所以要求：**要么有明确的解题请求，要么同时有"题目特征"和"求解特征"**。
 *
 * @param {string} text 消息文字（已剥离 @ 和占位符）
 * @param {{hasImage?:boolean}} [opts] 有没有带图（带图的题很常见）
 * @returns {{isProblem:boolean, why:string}}
 */
export function looksLikeProblem(text, opts = {}) {
  if (config.solve?.enable === false) return { isProblem: false, why: '解题模式已关' };
  const t = String(text ?? '').trim();
  const hasImage = opts.hasImage === true;

  // ⚠️ 先排除**服务器/群内事务** —— 那些里也有「算一下」「求解」这种词，
  //    但问的是服务器状态，不是数学题（真实踩过：「你算一下这周在线人数」）。
  if (/(服务器|在线人数|在线玩家|几个人|tps|整合包|模组|白名单|进服|开服|延迟|掉线)/i.test(t)) {
    return { isProblem: false, why: '问的是服务器的事' };
  }

  // ① 明确的解题请求 —— 最可靠
  const askSolve = /(解题|解答|做题|求解|求个解|帮我算|帮我解|算一下|算算|正确答案|答案是|给答案|看看这题|这题怎么|这题咋|这道题|这一题)/;
  if (askSolve.test(t)) return { isProblem: true, why: '明确要求解题' };

  // ② 题目特征词
  const problemWord =
    /(如图|已知|求证|证明|计算|化简|求值|最大值|最小值|取值范围|函数|方程|不等式|几何|三角形|四边形|圆心|切线|数列|概率|向量|导数|积分|受力|加速度|浮力|摩尔|化学式|电路|电阻|电压|电流|抛物线|椭圆|双曲线|正弦|余弦|正切|log|sin|cos|tan)/i;
  // ③ 求解特征词
  const solveWord = /(求|解|算|证|证明|等于多少|是多少|怎么求|如何求|过程|答案|求解)/;

  // ④ 题目结构：编号 + 问句（「例 3. ... 求 ...」「第(2)问」）
  const numbered = /(例\s*\d|第\s*\d+\s*题|第\s*[（(]?\d+[）)]?\s*问|\(\d\)\s*[^)]{0,20}(求|证|解)|（\d）)/;

  if (problemWord.test(t) && solveWord.test(t)) {
    return { isProblem: true, why: '含题目特征 + 求解特征' };
  }
  if (numbered.test(t) && solveWord.test(t)) {
    return { isProblem: true, why: '有题号 + 求解' };
  }
  // ⑤ 带图 + 短消息 → 很可能是「图就是题」
  //    （群里发张题图，配一句「这题」「解题」「看下这个」都很常见）
  if (hasImage && t.length <= 20) {
    // ⚠️ 但「看下这个」「看看这张」「瞅瞅那个」这种**纯指代**不算题 ——
    //    它只是让人看图，没说这是题。
    //    （用模式匹配而不是穷举词表：穷举会漏「看看这张」这种组合，我漏过一次。）
    const pureDemonstrative =
      /^[看瞅瞧瞄点开把给]\s*(一下|下|个|看|瞅)?\s*(这|那|上|下)?\s*(个|张|张图|幅|图|图片|截图|表情包|东西)?\s*[。.!！?？~～]*$/;
    // 光一个名词/指代（「这个」「图片」「那张」）也不算题
    const bareNoun =
      /^(这|那)?(个|张|幅|张图)?(图|图片|截图|表情包|东西|玩意)?[。.!！?？~～]*$/;
    const isJustPointing =
      pureDemonstrative.test(t) || bareNoun.test(t) || /^(这是|那是)?(什么|啥)[。.!！?？~～]*$/.test(t);

    // ⚠️⚠️ 2026-09-13 又加一道：**在问「信息」的语气不是题**。
    //
    //    真实踩过（用户截图）：他发了张图，然后 @它 说
    //      「**告诉我签300喂圆周率**」
    //    这句被 ⑤ 判成「图就是题」→ 进解题模式 → `max_tokens` 抬到 **24000**
    //    → 加上前面**连搜 5 轮**，整个请求 **60 秒超时** →
    //    群里就显示「⚠️ 模型调用出错了，请稍后再试」。
    //
    //    判据：**「告诉我 / 说给我 / 讲讲」问的是信息，不是解法**；
    //    真正的题不会这样开口（会说「解一下」「求」「求证」「答案是」）。
    //    而且要求**同句里没有求解词**，免得把「告诉我答案是几」也放过去。
    const chatTone =
      /^(告诉|跟我说|说给我|说下|讲讲|解释|介绍|问一下|我想知道|让我看看)/.test(
        t.replace(/^[\s@]+/, ''),
      ) && !/(解|求|算|证|答案|过程)/.test(t);

    if (chatTone) {
      return { isProblem: false, why: '带图，但语气是在问信息（不是求解题）' };
    }
    // ⚠️⚠️ 2026-09-20 加最后一道：**光"带图 + 短消息"不够，还得有求解或疑问的迹象**。
    //
    //    真实踩过（用户截图，20:21，群 200000001）：
    //      他发了张 **Minecraft 截图** + 一句「我这里有点出头了」→ 这条判成
    //      「图很可能就是题」→ 进解题模式 → 她当成"有人出题"，主动抢答
    //      「哪出头了，那栋蓝玻璃的？」，下一轮还答「我这边？老样子，坐着呢」。
    //      用户原话：**「又出现没有叫她但是把自己当成主角的情况了」**。
    //
    //    这条判据的初衷是"发题图 + 一句短话"，那种话里**一定有求解或疑问的痕迹**
    //    （这题／怎么做／求／解／算／多少／帮我看看…）；
    //    而**一句自述**（"我这里有点出头了"）两样都没有。
    //    ⇒ 要求二选一：有求解词，或有疑问意图。都没有 → 不是题。
    //    （⚠️ 真题目基本不会漏：出题的人总会带「求/解/算/多少/怎么」或者问号。）
    const solveHint =
      /(求|解|算|证|答案|过程|这题|题目|做题|怎么做|咋做|为什么|多少|是不是|对不对|帮我|看下|看看|瞅瞅)/;
    const doubtHint = /[?？]|吗|怎么|如何|为什么|多少|哪个|哪里|啥|什么/;
    if (!solveHint.test(t) && !doubtHint.test(t)) {
      return { isProblem: false, why: '带图，但只是一句自述（没有求解或疑问的迹象）' };
    }
    if (!isJustPointing) {
      return { isProblem: true, why: '带图 + 短消息（图很可能就是题）' };
    }
  }

  return { isProblem: false, why: '' };
}

/** 解题模式用的 max_tokens（比平时大得多，思考链很吃 token） */
export function solveMaxTokens() {
  return Number(config.solve?.maxTokens) || 24000;
}
