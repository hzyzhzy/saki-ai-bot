  cfg.outbox.checkIntervalMs = Math.max(30000, nz(cfg.outbox.checkIntervalMs, 60 * 1000));

  // ── 「通道假在线」的自救（2026-09-15 用户要求：「下次回 1200 应该自动重启」）──
  //
  // ⚠️ 这里只决定「**什么时候留一张请人重启的条子**」，真正重启协议端的是看门狗
