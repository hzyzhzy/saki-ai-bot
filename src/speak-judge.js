/**
 * 判断该不该接这句。
 *
 * @param {object} event 当前消息事件
 * @param {{context?:string, recentFromOthers?:boolean, voluntary?:string|null, questBrief?:string}} opts
 *   context：群聊最近记录（带说话人）
 *   recentFromOthers：最近是不是**别人在互相对话**（代码层已经判断出来的强信号）
 *   voluntary：如果是主动接话场景（question/mention/chat），传进来
 * @returns {Promise<{speak:boolean, why:string, length:'short'|'long', ms:number}>}
 */
export async function judgeSpeak(event, opts = {}) {
  const t0 = Date.now();
  // ⚠️ 判断失败时的兜底：**默认「说」**，不是「不说」。
  //
  //    为什么这么定：判断只是「锦上添花的筛选」，不是安全阀。
  //    如果默认「不说」，那判断一挂（网络抖、模型报错、超时），
  //    **机器人就永远不说话了** —— 一个小故障被放大成"完全不可用"，
  //    而且很难发现（表现只是"它怎么不理我"，日志里只有一行 debug）。
  //    所以**宁可多回一句，也不能整体哑掉**。
  //
  // ⚠️⚠️ 2026-10-15 加（用户：「**699 群到中午开始疯狂回消息**，可能是因为 llm 服务器的问题」）：
  //    **真因就是这个兜底** —— 上游 429/超时那阵子，这里每次失败都返回"照常说"，
  //    于是**群里每条消息她都想接** ⇒ 一小时刷了 40 条（平时 2~6 条）✗
  //    ⚠️ 而同一个群里**另一种"判不出来"**（判断节流）走的是**相反**的兜底
  //       （`bot.js` 那处：收紧度 > 2 ⇒ 这条不接）—— 两条判据不一致，这就是 bug ✗
  //    ⇒ 现在**兜底跟着收紧度走**：调用方传 `fallbackSilent: true`（收紧度 > 2 的群）
  //       就变成"**判不出来 ⇒ 不接**"（判不了就别抢话）；
  //       放得开的群（收紧度 ≤ 2）照旧"照常说"—— 那边要的就是像真人一样想说就说 ✓
  //    ⚠️ 不传 = 老行为（默认「说」）⇒ 别的调用方一个字不变 ✓
  const fallback = opts.fallbackSilent
    ? { speak: false, why: '判断失败（收紧度高，不接）', length: 'short', ms: 0 }
    : { speak: true, why: '判断失败（默认照常说）', length: 'short', ms: 0 };

  // ⚠️⚠️ 2026-10-06 加（用户：「**还是没回**」）：这条是**同类机器人**回的，
  //    而且**她自己刚跟它说过话**（是她挑起的）⇒ **直接说**，不劳模型判。
  //    实测踩过：judge 判「不说（对面是黑祥，不搭话，5921ms）」——
  //    那是前面"别陪着同类刷"那套引导教出来的，**把她自己开的头也掐了** ✗
  if (opts.peerJustReplied) {
    log.info('[说话判断] 同类在回她、而且是她先开的口 → 直接说（不判）');
    return { speak: true, why: '同类回的、她挑起的对话', length: 'short', ms: Date.now() - t0 };
  }

  if (config.speakJudge?.enable === false) {
    // 关掉判断时退回「说话」（保持旧行为，别让功能一关就全哑）
    return { speak: true, why: 'judge 已关闭', length: 'short', ms: 0 };
  }

  // ⚠️ 代码层已经确定的强信号，直接采信，不浪费一次调用
  //    ① 被 @ 了 → 必须回（这个在 decide 里已经处理，这里兜底）
  //    ② 明显是「别人在互相对话」且跟它无关 → 直接闭嘴
  if (opts.recentFromOthers && !opts.voluntary) {
    log.debug('[说话判断] 代码已判定「两人对话」，直接不说');
    return { speak: false, why: '别人在聊天', length: 'short', ms: Date.now() - t0 };
  }
  const segs = Array.isArray(event?.message) ? event.message : [];
  const text = segs
    .filter((s) => s.type === 'text')
    .map((s) => s.data?.text ?? '')
    .join('')
    .trim();

  // ⚠️⚠️ 2026-10-15 加（用户：「刚才 saki 发了一个**爱素**的视频，按道理应该算提到了爱音，
  //    应该要回的」）——
  //    起因（日志原文，爱音那个号）：`20:39:07 [说话判断] 不说（普通分享链接，没点名，2273ms）` ✗
  //    B站分享那种消息长这样：「这什么鬼东西【【爱素】谢谢，我不吃】 http://…」
  //    里面**带着群里某个号的角色名 / CP 名**，可判定模型不认识这些圈内词，
  //    就当成「别人顺手甩了条链接」⇒ 按死 ✗
  //    ⇒ 代码层直接判：消息里出现**跟我有关的 CP 名**（判据从 `anime/<库>.md` 的 CP 表抠出来，
  //      见 `cpNamesFor()`）⇒ **直接开口**，不劳模型（还省一次调用 ✓）
  //    ⚠️ 只认**跟我相关**的那些 —— 群里提「素世」不该让爱音接话 ✓
  if (text) {
    const myCp = cpNamesFor([persona.charName(), ...persona.callNames()]);
    const hit = myCp.find((n) => text.includes(n));
    if (hit) {
      log.info(`[说话判断] 消息里有跟我相关的叫法（${hit}）→ 直接说（不判）`);
      return { speak: true, why: `提到了我（${hit}）`, length: 'short', ms: Date.now() - t0 };
    }
  }
  const sender = event?.sender?.card || event?.sender?.nickname || String(event?.user_id ?? '');
  const isMedia = segs.some((s) => s.type === 'image' || s.type === 'face');

  // ⚠️⚠️ 2026-10-19 加（用户：「1，按你说的改」→ 再补一句「**不用一个人连刷，
  //    多个人连刷也算上**」）——
  //    **连着刷的时候不重复问模型**：
  //    群聊里大量是"刚有人说过，三秒后又来一条"（刷表情、「在吗」接「有人吗」、
  //    几个人一起聊），每条都单独问一次模型 ⇒ 判出来几乎全是"不说"，钱就这么烧掉的 ✗
  //    ⇒ 记下**上一次的结论**：上一条判"不说"、窗口内又来一条 ⇒ 直接不说、不判 ✓
  //
  //    ⚠️⚠️ **两条记录，窗口不一样**（用户要"多个人也算"，但跨人误杀风险更大）：
  //      ① `群:人` —— **同一个人**连着刷，窗口 `burstThrottleMs`（默认 10 秒）
  //      ② `群`     —— **群里任何人**刚说过，窗口**只有一半**（默认 5 秒，更保守）
  //         为什么要短一半：同一个人连发大概率是同一件事；**不同人**就可能是
  //         前一个人在闲聊、后一个人在问服务器 —— 那种必须照常判 ✗
  //
  //    ⚠️ 四条讲究（别把该接的也省掉）：
  //      ① **只复用"不说"** —— 上一条判"说"时不复用：他可能会追问，那得正常判；
  //      ② `inDialogue`（他正在跟我说话）时**完全不节流** —— 那是"对话没结束"，不是插话；
  //      ③ 兜底 / 失败的结论**不记**（那是猜的，拿它当依据会误杀一整串 ✗）；
  //      ④ @ / 点名 / CP 名 / 剧情追问 在**前面的闸**里就已经放行了，走不到这儿 ✓
  if (!opts.inDialogue && config.speakJudge?.burstThrottle !== false) {
    const winMs = Math.max(0, Number(config.speakJudge?.burstThrottleMs ?? 10000));
    const gid = String(event?.group_id ?? 'p');
    const tkSelf = `${gid}:${String(event?.user_id ?? '')}`;
    const tkGroup = `g:${gid}`;
    const winSelf = winMs;
    const winGroup = Math.round(winMs / 2);
    const nowMs = Date.now();
    // ⚠️ 顺手清掉过期的（别让这个 Map 无限涨）
    if (speakBurst.size > 200) {
      for (const [k, v] of speakBurst) if (nowMs - v.at > 60000) speakBurst.delete(k);
    }
    let hit = null;
    const pSelf = speakBurst.get(tkSelf);
    if (winSelf > 0 && pSelf && pSelf.speak === false && nowMs - pSelf.at < winSelf) {
      hit = { p: pSelf, who: '同一个人' };
    } else {
      const pG = speakBurst.get(tkGroup);
      if (winGroup > 0 && pG && pG.speak === false && nowMs - pG.at < winGroup) {
        hit = { p: pG, who: '群里刚有人' };
      }
    }
    if (hit) {
      log.info(
        `[说话判断] ${hit.who} ${Math.round((nowMs - hit.p.at) / 1000)} 秒前那条判过` +
          `"不说"（${hit.p.why}）⇒ **这条不判、直接不说**（省一次调用 ✓）`,
      );
      return {
        speak: false,
        why: `连着刷（${hit.p.why}）`,
        length: 'short',
        ms: Date.now() - t0,
      };
    }
    // 记下这两个 key，模型返回后一起写（见下面 `speakBurst.set`）
    opts.__burstKeys = [tkSelf, tkGroup];
  }

  // ⚠️ 「收紧度」滑块（2026-09-13 加，用户要求「给1级灵敏度加个能自由调节收紧度的滑块」
  //    并且「只对 1 生效」）。bot 那边算好一个 0~100 的数传进来，
  //    这里翻译成**给模型的自然语言标准** —— 光调概率不够，
  //    因为概率只决定"轮到它说没有"，不决定"它会不会说废话"。
  //
  //    onlyLevel1 为 true 时（即这个群是灵敏度 1）才带这段；
  //    2/3 档不带（那两档本来就安静，用户明确说滑块只管 1 档）。
  const strictNote = (() => {
    const s = Number(opts.strictness);
    if (!Number.isFinite(s)) return '';
    // ⚠️⚠️ 2026-10-19 改（用户：「1」）——
    //    **收紧度 ≥ 70 ⇒ 不管灵敏度几档都要带上这段**。
    //
    //    现场：699 群收紧度调到 95，13~16 点每小时还是回了 50~66 条 ✗
    //    真因：这段原来**只对灵敏度 1 档**生效（`strictnessOnlyLevel1`），
    //    而 `bot.js` 那边非 1 档时**压根不传 `strictness`**（传的是 `undefined`）
    //    ⇒ judge 每次看到的都是同一句"默认闭嘴，但这 5 种该说"，
    //      **它根本不知道现在是 95** ⇒ 群里一有人聊服务器/聊她，它就接 ✗
    if (s >= 70) {
      return [
        `⚠️⚠️ **这个群的「收紧度」是 ${s}/100（越高越少说话）—— 下面这段覆盖上面的「默认闭嘴」，标准更狠。**`,
        '',
        '**只有"不开口就是没礼貌 / 不开口他会出错"的时候才说。**',
        '',
        '## ✅ 该说（只有这几种）',
        '· 服务器相关的事实问题（有人吗 / 怎么进服 / 报错 / 规则 / 白名单）',
        '· 明确点名叫她、或者有人问她要东西',
        '· 有人接了她刚说的话、正在等她的下一句',
        '',
        '## 🚫 一律不说',
        '· 闲聊、玩梗、感叹、附和、「哈哈哈」「确实」「好家伙」、表情包',
        '· **别人之间在聊** —— 哪怕聊的正好是她懂的话题，哪怕她很想插一句',
        '· 只是想表示"我也在""我也觉得"',
        '',
        `· 拿不准 ⇒ **闭嘴**。这个档位下"少说一句"永远比"多说一句"安全。`,
        `· 按这个标准，这里一小时开口应该是**个位数** —— 不是一个小时几十条 ✗`,
      ].join('\n');
    }
    // ⚠️ 2026-10-19 加（用户：「**我建议50到70也在说话判定带上收紧度提示词，
    //    但是少一点，松一点**」）——
    //    50~69 是**默认区间往紧那边偏**（默认值就是 50）⇒ 给一段"稍微挑一点"的标准。
    //    ⚠️ 比 ≥70 那段**松得多**：那边是"一小时个位数"，这边只是"别为接而接" ✓
    //    ⚠️ 也不看灵敏度档位 —— 用户要的就是这个区间也带上 ✓
    if (s >= 50) {
      return [
        `⚠️ **这个群的「收紧度」是 ${s}/100（越高越少说话）—— 比默认稍微挑一点。**`,
        '',
        '## ✅ 说',
        '· 服务器相关的事实问题、报错、求助 → 说',
        '· 点名叫她、问她事 → 说',
        '· 有人接了她刚说的话、在等她下一句 → 说',
        '· 群友在聊**她确实懂**的话题，而且她能接得上一句有内容的 → 可以接',
        '',
        '## 🚫 别说',
        '· 纯附和（「哈哈哈」「确实」「好家伙」）而你没有新内容',
        '· 别人之间在聊私事 / 约时间 → 别插',
        '· 你只能**猜**、说不出具体东西的 → 别接',
        '',
        '· 拿不准 ⇒ **偏不说**。这个档位不要求你多话，但也别当个闷葫芦 ——',
        '  真有好接的一句就接，只是别"为接而接" ✓',
      ].join('\n');
    }
    // ⚠️ 下面"很松"那段**仍然只对灵敏度 1 档**有效 ——
    //    2/3 档本来就安静，别因为滑块低就把它们放开 ✓
    if (opts.strictnessOnlyLevel1 === false) return '';
    if (s <= 30) {
      return [
        '⚠️⚠️ **这个群现在调得很松（收紧度很低）—— 下面这段覆盖上面的「默认闭嘴」。**',
        '',
        '在这个档位下，**标准不是"非说不可"，而是"说了不突兀就说"**。',
        '用户明确要的是：**像个真人群友那样参与聊天**，不是当个只在被点名时才动的客服。',
        '',
        '## 该说（只要沾上一条就说）',
        '· 服务器相关、求助、报错 → **一定说**',
        '· 有人在**聊群里的事**（服务器、建站、游戏、群友、梗）→ **说**',
        '· 有人**分享日常**（买了什么、干了什么、吃了什么）→ **说**（真人会接一句）',
        '· 有人**吐槽 / 感叹 / 玩梗** → **说**（接个梗、跟着乐、反问一句都行）',
        '· 有人在**问所有人**（「你们觉得…」「有没有人…」）→ **说**',
        '· 有人**接了你刚说的话** → **一定说**',
        '',
        '## 不该说（只有这几种才闭嘴）',
        '· **只是笑/附和**（「哈哈哈」「哦」「嗯」）而你没新内容可加 → **不说**',
        '· 明显是**两个人之间的私事**（约时间、传文件、「@XX 你看」）',
        '· 你**完全接不上**、硬接会很怪（纯技术参数对轰、别人的私密话题）',
        '· 有人**正在吵架/生气** → 别掺和',
        '· 你**刚说过几乎一样的话**（避免重复）',
        '',
        '## 尺度参考',
        '· 一个真人群友在群里，**大概每三四条插一句** —— 这就是目标密度',
        '· **接得平淡没关系**（「哈？」「真的假的」都算），但**别为接而接**',
        '· 但**别连着刷** —— 你刚说过、下一句又紧跟，会显得很吵',
        '',
        '⚠️ 注意：**「完全放权、什么都接」是收紧度 0~2 档的事**',
        '（那一档连这个判断都跳过了）。这里是 5 附近，标准是',
        '**「有点挑，但基本都接」** —— 别退回成"默认闭嘴"。',
      ].join('\n');
    }
    return '';
  })();

  const user = [
    '# 群聊最近的记录（从旧到新）',
    opts.context || '（没有更多上下文）',
    '',
    '# 现在这条消息',
    `发送者：${sender}`,
    `内容：${text || (isMedia ? '[发了一张图/表情包]' : '（空的）')}`,
    opts.voluntary ? `（这条是系统筛出来的「可能值得接」的，类型：${opts.voluntary}）` : '',
    // ⚠️⚠️ 最强的信号：**他刚才就在跟我说话**（2026-09-13 加）
    //
    //    用户反馈（截图）：@ 它 → 它回「在。」→ 用户接着说「总共110」→ 它不接了。
    //    用户原话：「这很明显就是在和机器人交流，但是没 @ 的后面那一句就不回了，
    //    按道理这种应该**几乎大部分收紧度都应该继续对话**的，
    //    还是有**抽签回答**的感觉」。
    //
    //    对真人来说这根本不是判断题 —— **对话进行中，对方接着说，你就得接**。
    //    所以这里明确告诉它：这不是"要不要插话"，是"对话还没结束"。
    //    ⚠️ 除非对方明显是在跟**别人**说话（那种情况另说）。
    opts.inDialogue
      ? [
          '',
          '⚠️⚠️ **注意：刚才跟它说话的就是这个人，这是他接着说的下一句。**',
          '这**不是**"我该不该插话"的判断 —— 是**对话还在继续**。',
          '**默认应该接。** 只有当他说的话明显是转向别人（比如 @ 了别人、在回答别人的问题）时，才不说。',
          '真人绝不会在对话中途突然不理对方 —— 那很没礼貌，也很奇怪。',
        ].join('\n')
      : '',
    // ⚠️⚠️ 2026-09-17 修：群里**正在演剧情**时，群友那几句很可能是在跟她聊剧情 ——
    //    判断必须知道这件事，否则会当成"他们之间在闲聊"而闭嘴。
    //    实测（<主人> 截图）：她刚在群里讲了"给初华翻药箱"，群友追问「找到药了吗」「所以是谁拿的」
    //    「那我怎么攻略」，全被这个判断按死，紧接着群里有人直接问「你为啥不理他」。
    //    ⚠️ bot.js 那边已经**不让"别人在说话"短路**了；这里再让判断本身也知道剧情，
    //       免得它从别的角度（"随口玩梗""接不上"）又给按掉。
    opts.questBrief
      ? [
          '',
          '## ⚠️⚠️ 这个群**正在跑一条剧情，而且那条剧情是她本人在群里讲的**',
          opts.questBrief,
          '',
          '**所以判据要改**：如果这几句是在**追问 / 接续那条剧情**',
          '（「后来呢」「找到了吗」「所以是谁拿的」「那我怎么攻略」），',
          '那**就是在跟她说话** —— 既不是"他们之间在聊"，也不是"随口玩梗"。',
          '→ 这种情况**要说**（接着剧情答，或者像"话才说到一半呢"那样应一声）。',
          '⚠️ 但**别拿剧情当借口乱接**：跟这条剧情完全无关的闲聊，照旧按上面的默认（闭嘴）。',
        ].join('\n')
      : '',
    // ⚠️⚠️ **4 号：她自己的状态**（2026-09-15 加，用户要求"完善对话状态机"）
    //
    //    这一段让**密度由判断管**，而不是靠时间闸/额度闸：
    //      · 她几十秒前刚说过 → 可以闭嘴
    //      · 这一段她已经连说三句、对方只是附和 → 收住
    //      · 反过来，好几分钟没开口而话题她懂 → 可以说一句
    //    用户原话：「额度闸和冷却闸背后都是一样的」—— 都是"该不该再说一句"的
    //    粗糙代理；把真实状态摆给模型，就不必另加那两道闸。
    opts.dialogue
      ? ['', '# 你自己的状态（收住自己用）', String(opts.dialogue)]
          .join('\n')
      : '',
    strictNote,
    '',
    '我该不该开口？',
  ]
    .filter(Boolean)
    .join('\n');

  try {
    // ⚠️ 判断**必须限时**：它挡在每条消息的必经之路上。
    //    如果它卡住（网络慢、模型排队），整条消息就被堵在这里 ——
    //    streamChat 默认超时是 config.llm.timeout（**60 秒**），那对群聊是灾难。
    //    这里单独给一个短超时（默认 6 秒），超时就按兜底走（照常说）。
    const timeoutMs = Math.max(2000, Number(config.speakJudge?.timeoutMs) || 6000);
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(new Error('说话判断超时')), timeoutMs);

    let raw = '';
    try {
      for await (const d of streamChat(
        [
          { role: 'system', content: PROMPT },
          { role: 'user', content: user },
        ],
        ctl.signal,
      )) {
        raw += d;
        if (raw.length > 400) break; // 够解析了，别等它说完
      }
    } finally {
      clearTimeout(timer);
    }

    const m = String(raw).match(/\{[\s\S]*?\}/);
    if (!m) {
      // 判断没给出可解析的结果（比如被别的请求格式串了）→ 走兜底，别把机器人憋死
      log.debug(`[说话判断] 模型没给 JSON（${String(raw).slice(0, 50)}），按兜底「照常说」`);
      return { ...fallback, ms: Date.now() - t0 };
    }
    const j = JSON.parse(m[0]);
    const out = {
      speak: j.speak === true,
      why: String(j.why ?? '').slice(0, 20),
      length: j.length === 'long' ? 'long' : 'short',
      // ⚠️ 2026-10-04 加：`know` = "这件事我说得上话吗"。
      //    ⚠️ 只有模型**明确说 false** 才算"不懂"（`undefined` 当"没给"处理，
      //       代码层那道闸只认 `=== false`）—— 免得模型漏给字段就误杀一整类发言。
      know: j.know === true ? true : j.know === false ? false : undefined,
      // ⚠️ 2026-10-19 加（用户：「不是只是@她闭嘴要闭嘴，群友说的话有要她闭嘴的
      //    意图也要识别到」）—— `mute` = 这句话是**在让她闭嘴** ⇒ 调用方会让这个群
      //    静默 5 分钟（先答应一句再静默）。⚠️ 只有模型**明确说 true** 才算，
      //    `undefined` 当"没说"处理（免得漏个字段就把群静默掉 ✗）
      mute: j.mute === true,
      ms: Date.now() - t0,
    };
    // ⚠️ 2026-10-19：把这次结论记下来（下一句连着刷时复用）——
    //    只在**真判过**时记，兜底/失败的结论不记（那是猜的，拿它当依据会误杀 ✗）
    //    ⚠️ 两个 key 一起写：`群:人`（自己刷，长窗口）和 `群`（整群刷，短窗口）✓
    if (Array.isArray(opts.__burstKeys) && opts.__burstKeys.length) {
      for (const k of opts.__burstKeys) {
        speakBurst.set(k, { at: Date.now(), speak: out.speak, why: out.why });
      }
      delete opts.__burstKeys;
    }
    // ⚠️ 2026-09-15 用户要求（「把『判为不说』的理由提到 info 级」）：
    //    **不说的走 info**（这样"她为什么没接这句话"直接能在日志里看到），
    //    **说的仍然 debug** —— 说的量最大，提到 info 会把日志刷满。
    if (!out.speak) {
      log.info(`[说话判断] 不说（${out.why}，${out.ms}ms）→ 这条不接`);
    } else {
      log.debug(`[说话判断] 说（${out.why}，${out.ms}ms）`);
    }
    return out;
  } catch (e) {
    // 超时 / 网络错 / 解析错 → 按 `fallback` 走（默认「照常说」；收紧度高的群是「不接」）
    log.warn(
      fallback.speak
        ? `[说话判断] 出错（${e.message}），按兜底「照常说」`
        : `[说话判断] 出错（${e.message}）→ **这条不接**（收紧度高的群：判不了就别抢话）`,
    );
    return { ...fallback, ms: Date.now() - t0 };
  }
}
