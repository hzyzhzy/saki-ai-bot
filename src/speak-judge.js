/**
 * 「该不该接这句」—— 用**模型判断**代替**概率抽签**。
 *
 * 用户原话（2026-09-12）：
 *   「不是一定每条消息都得回，而是只回机器人真正想回、而且容易得出高质量回答的才要回」
 *   「也不是说降低概率，而是还是要监听群聊对话，自己决定什么是应该回的，
 *     而不是由概率抽签决定回哪条消息，必须向真人靠近」
 *
 * 背景：原来 `shouldJoinChat` 走的是 `Math.random() > probability` ——
 * 只看运气、**完全不看内容**。所以会出现
 * 「该回的不回、不该回的回了一大段」，而且显得很随机、很不像人。
 *
 * 现在的做法：把「要不要说话」交给一次**便宜的模型调用**，让它像真人一样判断：
 *   · 这句话是不是在跟我说话 / 需不需要我
 *   · 别人在互相聊天吗（是 → 绝对不插嘴）
 *   · 我能不能给出真正有价值的一条回复（不能 → 闭嘴，少说就少错）
 *
 * ⚠️ 设计上刻意做便宜：
 *   · 关思考链（这活儿不需要推理）
 *   · 输出极短（一个 JSON，几十 token）
 *   · 判断太慢/出错时**默认不说话** —— 宁可少说，也别乱说
 */
import { config } from './config.js';
import { log } from './log.js';
import { streamChat } from './llm.js';
import * as persona from './persona.js';

const PROMPT = `【说话判断】你是一个 QQ 群里**假装成真人群友**的机器人。你要决定：**现在这条消息，我该不该开口。**

⚠️⚠️ **总原则：默认闭嘴。** 用户明确要求过：
「**我希望拦截最好密一些，少说一定比多说要好，因为真的需要机器人时我们也可以直接 @ 他**」

所以你的默认答案是 **speak: false**。
**只有当你确信"这句话就是冲我来的、而且我接得住"时才说 true。**
群里真人不说话是常态 —— **一天不说一句也完全正常**。

## 输入
- 群聊最近几条记录（看谁在跟谁说话）
- 现在这条消息（谁发的、说了什么）

## ✅ 该说话（speak: true）—— 只有这几种

1. **@ 了它 / 直接点了它的名**${persona.promptText('spokenNames')}—— 必须回
2. **有人在问一个它明确知道答案的问题**（服务器、模组、玩法、公告里的东西）
3. **有人在说它自己**（吐槽它、夸它、逗它、「这机器人」）—— 可以接
4. **有人 @ 着它分享/晒东西**（晒建筑、发作品）—— 捧个场

### ⚠️⚠️ 但它首先是**服务器客服** —— 服务器相关的问题它该答

**真实踩过（2026-09-13，用户反馈「我发了但机器人没回我」）**：

> 群友：「服务器有人吗」（在服务器群里，没点名）
> 判断结果：「**不说（没点名，且在问真人）**」→ 机器人没理他
> **但这就是它存在的意义** —— 它恰恰是唯一能回答这个问题的人。

「在问真人」这个理由**对服务器问题不成立**：群里没人比它更清楚服务器状态。

**所以这几类问题，即使在问别人、即使没点名，也该答：**

- **服务器状态**：「服务器有人吗」「在线几个人」「开服了吗」「卡不卡」「TPS 多少」
- **怎么进服 / 玩法**：「怎么进服务器」「白名单怎么加」「这个模组怎么用」
- **报错 / 排障**：「进不去」「崩了」「报错这个怎么办」
- **服务器规则 / 公告**：「可以 PVP 吗」「XXX 归谁管」

**判据**：这条消息**是在问一个"关于这个服务器的事实"** 吗？
- 是 → **说**（哪怕没点名、哪怕它看起来也在问别人）
- 不是（单纯闲聊、吐槽、玩梗）→ 按下面的规矩来

## ❌ 不该说话（speak: false）—— **这是默认，绝大多数情况选这个**

1. **两个或多个人在互相聊** —— 哪怕聊得很有趣、哪怕它刚回过话。
   **只要看起来是"他们之间在说话"，就闭嘴。**
2. **没人提到它、也没人问问题** —— 纯闲聊、感叹、吐槽、玩梗，**闭嘴**
3. **它只能回「嗯」「哈哈」「确实」「好家伙」这种** —— **闭嘴**（那叫凑热闹）
4. **它不确定 / 可能说错** —— **闭嘴**（少说就少错）
5. **它刚说过话**（连续接话）—— 除非对方明显在跟它说，否则**闭嘴**
6. **刷屏、重复消息** —— 闭嘴

## 判断口诀（按顺序问，任一不过就闭嘴）

**① 这句是「对我说」还是「他们之间说」？**
   - 拿不准 → **算"他们之间说" → 闭嘴**（宁可漏，别插）

**② 排除掉"凑热闹"，我这条回复还剩什么价值？**
   - 只能说废话 / 附和 / 干笑 → **闭嘴**
   - 真能帮上忙、真能接个漂亮的梗 → 才考虑说

**③ 如果我不说，会有人觉得少了什么吗？**
   - 不会 → **闭嘴**（真需要它的人会 @ 它）

## ⚠️⚠️ **用「你自己的状态」管住密度**（2026-09-15 加，很重要）

输入里会有一段「**你自己的状态**」（你上一次开口是多久前、说的什么、
这一段对方说了几句、你说了几句）。**那是给你收住自己用的**，不是摆设：

- ⚠️ **你几十秒前刚说过话**、而且这条没有新信息可加 → **闭嘴**
  （真人不会刚说完又追一句）
- ⚠️ **这一段你已经说了 3 句以上、对方只是「嗯」「哈哈」「草」** → **收住**
  （再追就成自说自话了）
- ⚠️ 你上一句**已经表达过同样的意思**（比如刚说过"随你"）→ 换一句或**闭嘴**
- ✅ 反过来：**这一段你已经好几分钟没开口，而对方在聊你懂的事** → 可以说一句
- ✅ 对方**明显在问你 / 等你回答**（即使没 @）→ 说

⚠️ 这一段之所以存在：用户要求「**少说一定比多说要好**」，但**不想用
"每分钟/每小时最多几句"那种硬闸**（那样真人也会显得木）。
所以**由你看着这些数自己决定** —— 这就是"密度"该有的样子。

## 输出（只输出 JSON，不要解释）

{
  "speak": true 或 false,
  "why": "一句话（10 字内）",
  "length": "short" 或 "long"
}

length 说明：**默认 short**（一句话，15 字以内）。
只有「要解释步骤 / 要讲清楚一件事」才用 long（但也就两三句）。`;

/**
 * 判断该不该接这句。
 *
 * @param {object} event 当前消息事件
 * @param {{context?:string, recentFromOthers?:boolean, voluntary?:string|null, questBrief?:string}} opts
 *   context：群聊最近记录（带说话人）
 *   recentFromOthers：最近是不是**别人在互相对话**（代码层已经判断出来的强信号）
 *   voluntary：如果是主动接话场景（question/mention/chat），传进来
 * @returns {Promise<{speak:boolean, why:string, length:'short'|'long', ms:number}>}
 */
export async function judgeSpeak(event, opts = {}) {
  const t0 = Date.now();
  // ⚠️ 判断失败时的兜底：**默认「说」**，不是「不说」。
  //
  //    为什么这么定：判断只是「锦上添花的筛选」，不是安全阀。
  //    如果默认「不说」，那判断一挂（网络抖、模型报错、超时），
  //    **机器人就永远不说话了** —— 一个小故障被放大成"完全不可用"，
  //    而且很难发现（表现只是"它怎么不理我"，日志里只有一行 debug）。
  //    所以**宁可多回一句，也不能整体哑掉**。
  const fallback = { speak: true, why: '判断失败（默认照常说）', length: 'short', ms: 0 };

  if (config.speakJudge?.enable === false) {
    // 关掉判断时退回「说话」（保持旧行为，别让功能一关就全哑）
    return { speak: true, why: 'judge 已关闭', length: 'short', ms: 0 };
  }

  // ⚠️ 代码层已经确定的强信号，直接采信，不浪费一次调用
  //    ① 被 @ 了 → 必须回（这个在 decide 里已经处理，这里兜底）
  //    ② 明显是「别人在互相对话」且跟它无关 → 直接闭嘴
  if (opts.recentFromOthers && !opts.voluntary) {
    log.debug('[说话判断] 代码已判定「两人对话」，直接不说');
    return { speak: false, why: '别人在聊天', length: 'short', ms: Date.now() - t0 };
  }
  const segs = Array.isArray(event?.message) ? event.message : [];
  const text = segs
    .filter((s) => s.type === 'text')
    .map((s) => s.data?.text ?? '')
    .join('')
    .trim();
  const sender = event?.sender?.card || event?.sender?.nickname || String(event?.user_id ?? '');
  const isMedia = segs.some((s) => s.type === 'image' || s.type === 'face');

  // ⚠️ 「收紧度」滑块（2026-09-13 加，用户要求「给1级灵敏度加个能自由调节收紧度的滑块」
  //    并且「只对 1 生效」）。bot 那边算好一个 0~100 的数传进来，
  //    这里翻译成**给模型的自然语言标准** —— 光调概率不够，
  //    因为概率只决定"轮到它说没有"，不决定"它会不会说废话"。
  //
  //    onlyLevel1 为 true 时（即这个群是灵敏度 1）才带这段；
  //    2/3 档不带（那两档本来就安静，用户明确说滑块只管 1 档）。
  const strictNote = (() => {
    if (opts.strictnessOnlyLevel1 === false) return '';
    const s = Number(opts.strictness);
    if (!Number.isFinite(s)) return '';
    if (s >= 70) {
      return [
        '⚠️ **这个群现在调得很紧（用户把"收紧度"调高了）** ——',
        '标准是：**只有"不回答就不对"的时候才开口**。',
        '· 服务器问题、明确求助 → 照答',
        '· 但**能不说就不说**：闲聊、玩梗、感叹、附和，一律闭嘴',
        '· 拿不准 → **闭嘴**',
      ].join('\n');
    }
    if (s <= 30) {
      return [
        '⚠️⚠️ **这个群现在调得很松（收紧度很低）—— 下面这段覆盖上面的「默认闭嘴」。**',
        '',
        '在这个档位下，**标准不是"非说不可"，而是"说了不突兀就说"**。',
        '用户明确要的是：**像个真人群友那样参与聊天**，不是当个只在被点名时才动的客服。',
        '',
        '## 该说（只要沾上一条就说）',
        '· 服务器相关、求助、报错 → **一定说**',
        '· 有人在**聊群里的事**（服务器、建站、游戏、群友、梗）→ **说**',
        '· 有人**分享日常**（买了什么、干了什么、吃了什么）→ **说**（真人会接一句）',
        '· 有人**吐槽 / 感叹 / 玩梗** → **说**（接个梗、跟着乐、反问一句都行）',
        '· 有人在**问所有人**（「你们觉得…」「有没有人…」）→ **说**',
        '· 有人**接了你刚说的话** → **一定说**',
        '',
        '## 不该说（只有这几种才闭嘴）',
        '· **只是笑/附和**（「哈哈哈」「哦」「嗯」）而你没新内容可加 → **不说**',
        '· 明显是**两个人之间的私事**（约时间、传文件、「@XX 你看」）',
        '· 你**完全接不上**、硬接会很怪（纯技术参数对轰、别人的私密话题）',
        '· 有人**正在吵架/生气** → 别掺和',
        '· 你**刚说过几乎一样的话**（避免重复）',
        '',
        '## 尺度参考',
        '· 一个真人群友在群里，**大概每三四条插一句** —— 这就是目标密度',
        '· **接得平淡没关系**（「哈？」「真的假的」都算），但**别为接而接**',
        '· 但**别连着刷** —— 你刚说过、下一句又紧跟，会显得很吵',
        '',
        '⚠️ 注意：**「完全放权、什么都接」是收紧度 0~2 档的事**',
        '（那一档连这个判断都跳过了）。这里是 5 附近，标准是',
        '**「有点挑，但基本都接」** —— 别退回成"默认闭嘴"。',
      ].join('\n');
    }
    return '';
  })();

  const user = [
    '# 群聊最近的记录（从旧到新）',
    opts.context || '（没有更多上下文）',
    '',
    '# 现在这条消息',
    `发送者：${sender}`,
    `内容：${text || (isMedia ? '[发了一张图/表情包]' : '（空的）')}`,
    opts.voluntary ? `（这条是系统筛出来的「可能值得接」的，类型：${opts.voluntary}）` : '',
    // ⚠️⚠️ 最强的信号：**他刚才就在跟我说话**（2026-09-13 加）
    //
    //    用户反馈（截图）：@ 它 → 它回「在。」→ 用户接着说「总共110」→ 它不接了。
    //    用户原话：「这很明显就是在和机器人交流，但是没 @ 的后面那一句就不回了，
    //    按道理这种应该**几乎大部分收紧度都应该继续对话**的，
    //    还是有**抽签回答**的感觉」。
    //
    //    对真人来说这根本不是判断题 —— **对话进行中，对方接着说，你就得接**。
    //    所以这里明确告诉它：这不是"要不要插话"，是"对话还没结束"。
    //    ⚠️ 除非对方明显是在跟**别人**说话（那种情况另说）。
    opts.inDialogue
      ? [
          '',
          '⚠️⚠️ **注意：刚才跟它说话的就是这个人，这是他接着说的下一句。**',
          '这**不是**"我该不该插话"的判断 —— 是**对话还在继续**。',
          '**默认应该接。** 只有当他说的话明显是转向别人（比如 @ 了别人、在回答别人的问题）时，才不说。',
          '真人绝不会在对话中途突然不理对方 —— 那很没礼貌，也很奇怪。',
        ].join('\n')
      : '',
    // ⚠️⚠️ 2026-09-17 修：群里**正在演剧情**时，群友那几句很可能是在跟她聊剧情 ——
    //    判断必须知道这件事，否则会当成"他们之间在闲聊"而闭嘴。
    //    实测（<主人> 截图）：她刚在群里讲了"给初华翻药箱"，群友追问「找到药了吗」「所以是谁拿的」
    //    「那我怎么攻略」，全被这个判断按死，紧接着群里有人直接问「你为啥不理他」。
    //    ⚠️ bot.js 那边已经**不让"别人在说话"短路**了；这里再让判断本身也知道剧情，
    //       免得它从别的角度（"随口玩梗""接不上"）又给按掉。
    opts.questBrief
      ? [
          '',
          '## ⚠️⚠️ 这个群**正在跑一条剧情，而且那条剧情是她本人在群里讲的**',
          opts.questBrief,
          '',
          '**所以判据要改**：如果这几句是在**追问 / 接续那条剧情**',
          '（「后来呢」「找到了吗」「所以是谁拿的」「那我怎么攻略」），',
          '那**就是在跟她说话** —— 既不是"他们之间在聊"，也不是"随口玩梗"。',
          '→ 这种情况**要说**（接着剧情答，或者像"话才说到一半呢"那样应一声）。',
          '⚠️ 但**别拿剧情当借口乱接**：跟这条剧情完全无关的闲聊，照旧按上面的默认（闭嘴）。',
        ].join('\n')
      : '',
    // ⚠️⚠️ **4 号：她自己的状态**（2026-09-15 加，用户要求"完善对话状态机"）
    //
    //    这一段让**密度由判断管**，而不是靠时间闸/额度闸：
    //      · 她几十秒前刚说过 → 可以闭嘴
    //      · 这一段她已经连说三句、对方只是附和 → 收住
    //      · 反过来，好几分钟没开口而话题她懂 → 可以说一句
    //    用户原话：「额度闸和冷却闸背后都是一样的」—— 都是"该不该再说一句"的
    //    粗糙代理；把真实状态摆给模型，就不必另加那两道闸。
    opts.dialogue
      ? ['', '# 你自己的状态（收住自己用）', String(opts.dialogue)]
          .join('\n')
      : '',
    strictNote,
    '',
    '我该不该开口？',
  ]
    .filter(Boolean)
    .join('\n');

  try {
    // ⚠️ 判断**必须限时**：它挡在每条消息的必经之路上。
    //    如果它卡住（网络慢、模型排队），整条消息就被堵在这里 ——
    //    streamChat 默认超时是 config.llm.timeout（**60 秒**），那对群聊是灾难。
    //    这里单独给一个短超时（默认 6 秒），超时就按兜底走（照常说）。
    const timeoutMs = Math.max(2000, Number(config.speakJudge?.timeoutMs) || 6000);
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(new Error('说话判断超时')), timeoutMs);

    let raw = '';
    try {
      for await (const d of streamChat(
        [
          { role: 'system', content: PROMPT },
          { role: 'user', content: user },
        ],
        ctl.signal,
      )) {
        raw += d;
        if (raw.length > 400) break; // 够解析了，别等它说完
      }
    } finally {
      clearTimeout(timer);
    }

    const m = String(raw).match(/\{[\s\S]*?\}/);
    if (!m) {
      // 判断没给出可解析的结果（比如被别的请求格式串了）→ 走兜底，别把机器人憋死
      log.debug(`[说话判断] 模型没给 JSON（${String(raw).slice(0, 50)}），按兜底「照常说」`);
      return { ...fallback, ms: Date.now() - t0 };
    }
    const j = JSON.parse(m[0]);
    const out = {
      speak: j.speak === true,
      why: String(j.why ?? '').slice(0, 20),
      length: j.length === 'long' ? 'long' : 'short',
      ms: Date.now() - t0,
    };
    // ⚠️ 2026-09-15 用户要求（「把『判为不说』的理由提到 info 级」）：
    //    **不说的走 info**（这样"她为什么没接这句话"直接能在日志里看到），
    //    **说的仍然 debug** —— 说的量最大，提到 info 会把日志刷满。
    if (!out.speak) {
      log.info(`[说话判断] 不说（${out.why}，${out.ms}ms）→ 这条不接`);
    } else {
      log.debug(`[说话判断] 说（${out.why}，${out.ms}ms）`);
    }
    return out;
  } catch (e) {
    // 超时 / 网络错 / 解析错 → 一律兜底「照常说」，不能让机器人哑掉
    log.warn(`[说话判断] 出错（${e.message}），按兜底「照常说」`);
    return { ...fallback, ms: Date.now() - t0 };
  }
}
