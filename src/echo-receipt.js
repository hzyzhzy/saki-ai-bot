/**
 * 「回执空壳句」判据 —— 单独一个小模块，两个地方共用。
 *
 * ⚠️⚠️ 2026-10-26 建（用户：「**就是 bot 回复指令的固定句子进上下文而且还没修好**」）
 *
 * 起因：`bot.js` 开剧情时会**硬编码发一条回执**（`sendToGroup(gid, '行，就按这个来，等我一下（')`），
 *   它本来是"给人看一眼，表示我收到了"，**不该进任何上下文**。可它有**三条路**会漏进去：
 *
 *   | # | 落点 | 之前管没管 |
 *   | --- | --- | --- |
 *   | ① | `state/recent.json`（记**她自己的**话，`recent.rememberBot()`） | 管了（2026-10-16），但要求"上游是主人/同类池" ⇒ 伪造 event 时失效 ✗ |
 *   | ② | `state/recent.json`（记**对方号**的话，`recent.remember()`） | 2026-10-26 补的 |
 *   | ③ | `state/quest.json`（**剧情记录**：`pending` / `stages[].replies` / `interludes`） | **一条都没管** ✗ ← 用户报的就是这条 |
 *
 *   实证：`/byGroup/1131801543/recent/5/stages/3/replies/0/text` = 「行，就按这个来，等我一下（」
 *   ⇒ `advance()` 每一段都把它喂给模型 ⇒ 两个号开始互相接：
 *      「又等我一下？」「行，那我等你（」—— 群里看着像两个复读机 ✗✗
 *
 * 判据**故意窄**：整句话**就是**一个"等你/等我"的空壳，没有别的意思。
 *   ⚠️ 我第一版用宽正则（含 `好了|我看看|等我`）直接清库，**误删了 6 条正常台词**：
 *     「这一遍也没白说，我不是躺好了嘛」「钥匙明天早上我等你，别迟到」
 *     「她要是还盯着你，那就是在等你再往前一点」「这话等你清醒的时候再说一遍」✗✗
 *   ⇒ 现在：去标点 → 去掉末尾括号（里面通常是动作描写）→ 剥语气前缀（嗯/行/好/诶 + 那/就）
 *     → **剩下的必须正好是那几个空壳短语** ✓
 */

/**
 * @param {string} text
 * @returns {boolean}
 */
export function isEchoReceipt(text) {
  let s = String(text ?? '').trim();
  if (!s) return false;
  if (s.length > 40) return false; // 长句不可能是空壳，先挡掉（省得逐条正则）
  s = s.replace(/[\s，,。.！!？?、…~～；;：:]/g, ''); // 去标点
  s = s.replace(/[（(].*$/, ''); // 去掉末尾括号及其内容（动作描写）
  s = s.replace(/^(嗯|行|好|哦|噢|诶|哎)+/, ''); // 语气前缀
  s = s.replace(/^(那|就)+/, ''); // 「那我等你」「就等我一下」
  if (!s || s.length > 12) return false;
  return (
    /^(就?按这个来|就?按这个做|就?往这个方向走|往这个方向走)(等我一下|等我|等你|等你一下)?$/.test(s) ||
    /^(我?等你(一下|一会儿)?|等我(一下|一会儿)?|等你一下|你等我一下)$/.test(s)
  );
}
