/**
 * 群消息筛选（B站视频用）—— **合成和挑选共用一份**
 *
 * 为什么要抽出来：`pick-chat` 给模型看的是"候选列表"，模型回的是**列表下标**；
 * 而合成端`bili-intro3` 按同一份下标取消息 ⇒ 两边过滤规则必须完全一致，
 * 各写一份必然错位（改一处漏一处，取到的是别的消息）✗
 *
 * 这里只做**内容边界**过滤（政治/辱骂/外链/纯图片）。
 * ⚠️ 「哪条消息适合放在第几句台词旁边」这种**理解内容**的判断不在这里做 ——
 *    那必须交给模型（AGENTS 铁律：非必要不用关键词快判）
 */

// ⚠️ 这是**内容边界**过滤（上 B 站会被限流/下架的东西），不是"猜人话"，
//    所以用关键词是对的；但只放**明确无疑**的脏话组合，别放单字缩写（`nm` 会误伤别的词）
const BAD = /(俄罗斯|乌克兰|俄方|击毙|政治|政府|习近平|台湾|港独|法轮|六四|废物|傻逼|煞笔|沙比|脑残|操你|去死|妈的|滚蛋|tmd|nmsl|wcnm|cnm|rnm)/i;
const URL_RE = /https?:\/\/|warthunder|\.com|\.cn/i;

/**
 * 收不出来的东西（用户 2026-10-21：「不要筛连带有图片和其他放不进 html 的进聊天记录，
 * 因为本来就没办法显示，只能筛纯文字的」）
 *
 * ⚠️ 必须**整条剔除**，不是"删掉标记留住文字"：
 *   一条消息带 [图片] + 一句话，HTML 里那句话能显示，但图片只能画成假色块 ⇒
 *   观众一眼看出是假的 ✗ 所以只要带附件标记，整条不要。
 * ⚠️ 例外：[引用#xxx] 是**能显示**的（HTML 里有引用框），不算附件。
 */
const ATTACH = /\[(图片|表情包|QQ表情|动画表情|语音|视频|文件[:：][^\]]*|合并转发|分享[:：][^\]]*|分享|卡片|位置|名片|红包|戳一戳)\]/;
// 「（@了机器人）」同理 —— 协议端给纯 @ 消息塞的占位符，没有正文
const AT_PLACEHOLDER = /[（(]\s*@?了?\s*(机器人|我)\s*[)）]|\[@?机器人\]/;

/** 从群消息数组里取适合上 B 站的候选（保持原顺序） */
// ⚠️ 窗口从 170 放大到 400：纯文字消息本来就少，窗口太小会不够铺满画面
export function filterMessages(all, { window = 400 } = {}) {
  return all.slice(-window).filter((m) => {
    const t = String(m.text || '');
    if (BAD.test(t) || URL_RE.test(t)) return false;
    // 带附件 / 占位符的一律整条剔除（HTML 里表现不出来，画出来就是假的）
    if (ATTACH.test(t) || AT_PLACEHOLDER.test(t)) return false;
    // 去掉引用前缀之后必须还有真文字
    const noQuote = t.replace(/\[引用#[^\]]*\]/g, '').replace(/\s+/g, ' ').trim();
    if (!noQuote) return false;
    return true;
  });
}

/** 消息的可读文本（给模型看的时候去掉附件占位符） */
export function cleanText(m) {
  return String(m.text || '')
    .replace(/\[(图片|表情包|QQ表情|合并转发|语音)\]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * 消息的**稳定指纹**
 *
 * ⚠️⚠️ 为什么必须有它（2026-10-21 真事故）：
 *   agent 挑消息时看的是"候选列表的下标"，而候选是 `all.slice(-170)` —— **群消息一直在进**，
 *   窗口会滑动。实测两次都是 143 条、数量校验通不出问题，但**内容完全变了**
 *   ⇒ 按旧下标取出来的是别的消息：明明剔掉了「房租该交了」，成片里照样出现 ✗
 *   ⇒ 挑选结果必须存**指纹**，取的时候按指纹匹配，跟窗口滑不滑没关系 ✓
 */
export const keyOf = (m) =>
  m.messageId ? `id:${m.messageId}` : `tx:${cleanText(m)}`;
